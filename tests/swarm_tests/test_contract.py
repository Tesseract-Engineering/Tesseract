"""Contract tests: the committed JSON Schemas are current, and every line of
the sample run validates against both the models and those schemas."""

import json
from pathlib import Path

import pytest

from swarm import schema
from swarm.records import Manifest, parse_line

ROOT = Path(__file__).resolve().parents[2]
SAMPLE = ROOT / "samples" / "run-0" / "runs"


def test_committed_schemas_are_current():
    assert schema.main(["--check"]) == 0, "run python -m swarm.schema"


def sample_lines():
    for path in sorted(SAMPLE.rglob("*.jsonl")):
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            yield pytest.param(line, id=f"{path.relative_to(SAMPLE)}:{n}")


@pytest.mark.parametrize("line", list(sample_lines()))
def test_sample_lines_validate(line):
    record = parse_line(line)
    jsonschema = pytest.importorskip("jsonschema")
    jsonschema.validate(json.loads(line), json.loads(
        (schema.OUT / f"{record.record_type}.json").read_text(encoding="utf-8")))


def test_sample_has_every_record_type_and_complete_manifests():
    kinds = {parse_line(line.values[0]).record_type for line in sample_lines()}
    assert kinds == {"item", "extraction", "tombstone", "acl_update", "group", "identity"}
    runs = [p for p in SAMPLE.glob("*/*") if p.is_dir()]
    assert len(runs) == 4
    for run in runs:
        manifest = Manifest.model_validate_json((run / "_manifest.json").read_text(encoding="utf-8"))
        assert manifest.status == "complete" and manifest.run_id == run.name
        assert sorted(p.relative_to(run).as_posix() for p in run.rglob("*.jsonl")) == manifest.files


def test_sample_is_what_the_builder_writes(tmp_path):
    """samples/run-0 is regenerated by samples/make_run0.py; a hand edit that
    the builder would not produce fails here."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("make_run0", ROOT / "samples" / "make_run0.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.build(tmp_path)
    built = {p.relative_to(tmp_path / "runs"): p.read_bytes() for p in (tmp_path / "runs").rglob("*") if p.is_file()}
    committed = {p.relative_to(SAMPLE): p.read_bytes() for p in SAMPLE.rglob("*") if p.is_file()}
    assert built == committed, "run python samples/make_run0.py"


def test_sample_paths_check_out_on_windows():
    """Windows refuses these characters in a file or folder name; a run id
    with colons once kept the sample from checking out there."""
    assert [p for p in SAMPLE.rglob("*") if set(p.name) & set('<>:"|?*\\')] == []
